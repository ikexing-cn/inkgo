//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"writer/internal/grapheme/tablegen"
)

func main() {
	simple := tablegen.Tables()
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by go run gen.go; DO NOT EDIT.\n\npackage grapheme")
	fmt.Fprintln(&b, "\nvar bmpSimple = [8192]byte{")
	for i, v := range simple {
		if v != 0 {
			fmt.Fprintf(&b, "%d: 0x%02x,\n", i, v)
		}
	}
	fmt.Fprintln(&b, "}")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("tables_generated.go", out, 0644); err != nil {
		panic(err)
	}
}
